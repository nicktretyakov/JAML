use crate::domain::Renderable;
use crate::concurrency::ParallelPageGenerator;
use crate::core::{CmsResult, ContentRepository, EventBus, SiteBuilder, StaticWriter};
use crate::domain::{DomainEvent, SiteConfig, SiteManifest};
use async_trait::async_trait;
use chrono::Utc;
use std::sync::Arc;
use tracing::info;

pub struct ConcurrentBuildService {
    repo: Arc<dyn ContentRepository>,
    generator: Arc<ParallelPageGenerator>,
    writer: Arc<dyn StaticWriter>,
    events: Arc<dyn EventBus>,
}

impl ConcurrentBuildService {
    pub fn new(
        repo: Arc<dyn ContentRepository>,
        generator: Arc<ParallelPageGenerator>,
        writer: Arc<dyn StaticWriter>,
        events: Arc<dyn EventBus>,
    ) -> Self {
        Self {
            repo,
            generator,
            writer,
            events,
        }
    }
}

#[async_trait]
impl SiteBuilder for ConcurrentBuildService {
    async fn build(&self, config: &SiteConfig) -> CmsResult<SiteManifest> {
        self.events.publish(DomainEvent::BuildStarted { at: Utc::now() });

        let start = std::time::Instant::now();
        info!("Starting concurrent static site build...");

        // Ensure output dir
        self.writer.ensure_dir(&config.output_dir)?;

        // Load published content
        let items = self.repo.list_published().await?;
        info!("Loaded {} published items", items.len());

        // Parallel generation
        let (pages, _gen_ms) = self.generator.generate_all(&items, config)?;

        // Copy static assets
        self.writer
            .copy_static_dir(&config.static_dir, &config.output_dir.join("static"))?;

        // Generate index page
        let _index_ctx = serde_json::json!({
            "site": {
                "title": config.title,
                "description": config.description,
                "base_url": config.base_url,
            },
            "posts": items.iter().map(|i| i.context()).collect::<Vec<_>>(),
            "generated_at": Utc::now().to_rfc3339(),
        });

        // We need a template engine reference – for simplicity we write a basic index
        // In real code we'd inject it; here we generate a minimal index.
        let index_html = format!(
            r#"<!DOCTYPE html>
<html lang="{}">
<head>
  <meta charset="utf-8">
  <title>{}</title>
  <meta name="description" content="{}">
  <link rel="stylesheet" href="/static/css/main.css">
</head>
<body>
  <header><h1>{}</h1><p>{}</p></header>
  <main>
    <h2>Последние публикации</h2>
    <ul>
      {}
    </ul>
  </main>
  <footer>Generated by Solid SSG CMS · {}</footer>
  <script src="/static/js/app.js"></script>
</body>
</html>"#,
            config.language,
            config.title,
            config.description,
            config.title,
            config.description,
            items
                .iter()
                .map(|i| format!(
                    r#"<li><a href="/{}.html">{}</a> <small>by {}</small></li>"#,
                    i.slug, i.title, i.author
                ))
                .collect::<Vec<_>>()
                .join("\n"),
            Utc::now().to_rfc3339()
        );
        self.writer.write_file("index.html", &index_html)?;

        let duration = start.elapsed().as_millis() as u64;
        let manifest = SiteManifest {
            generated_at: Utc::now(),
            pages: pages.clone(),
            total_items: items.len(),
            build_duration_ms: duration,
        };

        // Write manifest
        let manifest_json = serde_json::to_string_pretty(&manifest)?;
        self.writer.write_file("manifest.json", &manifest_json)?;

        self.events.publish(DomainEvent::BuildFinished {
            at: Utc::now(),
            duration_ms: duration,
            pages: pages.len(),
        });

        info!("Build complete in {} ms, {} pages", duration, pages.len());
        Ok(manifest)
    }
}
